            }
            db.ExpenseVouchers.Add(new ExpenseVoucher { TenantId = tenantId, BranchId = branch.Id,
                VoucherCode = $"DM-{tag}-CP-{index}", BeneficiaryName = "Đơn vị dịch vụ demo", Category = "Điện nước",
                Amount = 20000, Status = ExpenseVoucherStatus.Approved, ExpenseDate = now, CreatedAt = now, Note = "Chi phí demo" });
