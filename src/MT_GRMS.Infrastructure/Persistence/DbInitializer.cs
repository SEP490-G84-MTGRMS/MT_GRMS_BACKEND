        await db.SaveChangesAsync(ct);
    }

    private static async Task SeedAdminAsync(AppDbContext db, CancellationToken ct)
    {
        // Reuse the existing administrator instead of creating a second demo administrator.
        if (await db.Users.IgnoreQueryFilters().AnyAsync(u => u.IsAdmin && !u.IsDeleted, ct)) return;
        if (await db.Users.IgnoreQueryFilters().AnyAsync(u => u.UserName == "admin" || u.Id == "usr_super_admin", ct))
            throw new InvalidOperationException("Không thể tạo demo Admin do tên hoặc ID đã được sử dụng.");
        db.Users.Add(CreateUser("usr_super_admin", "admin", "Quản trị THViet Demo", "0901000000", "Admin@123456", true));
        await db.SaveChangesAsync(ct);
    }

    private static User CreateUser(string id, string username, string name, string phone, string password, bool admin = false)
