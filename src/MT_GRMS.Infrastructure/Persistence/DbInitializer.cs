    private static async Task SeedScenarioAsync(AppDbContext db, Scenario scenario, int number, string id, CancellationToken ct)
    {
        var now = DateTime.UtcNow;
        var paid = scenario.Plan is "STANDARD" or "PRO";
        var owner = CreateUser("demo-owner-" + scenario.Key, "demo." + scenario.Key,
            "Chủ cửa hàng " + scenario.Name, $"091000000{number}", "Demo@123456");
        owner.TrialConsumedAt = scenario.State == "NO_PLAN" ? null : now.AddDays(-5);
        if (scenario.State == "TRIAL") owner.TrialConsumedAt = now;
        db.Users.Add(owner);
        var tenant = new Tenant {
            Id = id, Code = "DEMO-" + scenario.Key.ToUpperInvariant(), Subdomain = "demo-" + scenario.Key,
            Name = scenario.Name, City = "Hà Nội", Address = "Địa chỉ cửa hàng demo, Hà Nội", Hotline = owner.Phone,
            CurrentPlan = scenario.Plan, SubscriptionStatus = scenario.State,
            Status = scenario.Key == "locked" ? "LOCKED" : scenario.Key == "grace" ? "GRACE_PERIOD" : "ACTIVE",
            SubscriptionExpiresAt = scenario.Plan == null ? null : now.AddDays(scenario.DaysLeft),
            FirstPaidAt = paid ? now.AddDays(scenario.DaysLeft - (scenario.Key == "pro-extra" ? 365 : scenario.Key == "pro" ? 90 : 30)) : null,
            TrialStartedAt = scenario.State == "TRIAL" ? now : null,
            TrialExpiresAt = scenario.State == "TRIAL" ? now.AddDays(3) : null,
            HasStaffManagementAddon = scenario.Plan == "STANDARD",
            ExtraBranches = scenario.Key == "pro-extra" ? 1 : 0,
            GracePeriodExpiresAt = scenario.Key is "grace" or "locked" ? now.AddDays(scenario.DaysLeft + 7) : null,
            LockType = scenario.Key == "locked" ? "SOFT" : null,
            LockReason = scenario.Key == "locked" ? "Dữ liệu demo: quá thời gian gia hạn" : null,
            LockedAt = scenario.Key == "locked" ? now.AddDays(-3) : null
