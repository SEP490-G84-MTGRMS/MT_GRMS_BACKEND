                    ON "Notifications" ("TenantId", "RecipientUserId", "IsRead", "CreatedAt");
                """);
            await WalletTopupSchemaMigration.ApplyAsync(context);
        }

        schemaTimer.Stop();
        logger?.LogInformation("Database schema initialization phase completed in {ElapsedMilliseconds} ms.", schemaTimer.ElapsedMilliseconds);
        if (!seedSampleData)
        {
            logger?.LogInformation("SeedSampleData=false — chỉ đồng bộ schema, bỏ qua nạp dữ liệu mẫu.");
            return;
        }

        var seedTimer = Stopwatch.StartNew();
        await SeedDemoAsync(context);
        logger?.LogInformation("Scenario demo seed completed in {ElapsedMilliseconds} ms.", seedTimer.ElapsedMilliseconds);
    }

