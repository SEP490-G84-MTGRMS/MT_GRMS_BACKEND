                db.ShiftConfigs.Add(shift);
                for (var employeeIndex = 1; employeeIndex <= 3; employeeIndex++)
                {
                    var staff = CreateUser($"demo-{scenario.Key}-{b}-{employeeIndex}", $"demo.{scenario.Key}.{b}.{employeeIndex}",
                        $"Nhân viên demo {b}-{employeeIndex}", $"092{number:00}{b:00}{employeeIndex:000}", "Demo@123456");
                    db.Users.Add(staff);
                    db.TenantUsers.Add(new TenantUser { TenantId = id, UserId = staff.Id, Role = employeeIndex == 1 ? "BRANCH_MANAGER" : "STAFF" });
                    var employee = new Employee { TenantId = id, BranchId = branch.Id, UserId = staff.Id,
                        EmployeeCode = $"DM-{scenario.Key}-{b}-{employeeIndex}", FullName = staff.FullName, Phone = staff.Phone!, Email = staff.Email,
