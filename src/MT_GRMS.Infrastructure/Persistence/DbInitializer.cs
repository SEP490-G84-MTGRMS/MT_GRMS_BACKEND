        db.Branches.AddRange(branches);
        if (paid) await SeedPurchasesAsync(db, tenant, scenario, ct);
        if (scenario.State != "NO_PLAN")
        {
            foreach (var (branch, b) in branches.Select((branch, i) => (branch, i + 1)))
            {
                var shift = new ShiftConfig { TenantId = id, BranchId = branch.Id, ShiftCode = $"DM-{scenario.Key}-{b}",
