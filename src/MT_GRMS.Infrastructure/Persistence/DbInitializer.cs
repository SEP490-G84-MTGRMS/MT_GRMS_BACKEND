        var category = new Category { TenantId = tenantId, CategoryCode = "DM-" + tag, Name = "Hàng tạp hóa demo" };
        db.Categories.Add(category);
        var products = new List<Product>();
        foreach (var (name, unit, cost, price, stock) in new[] {
            ("Gạo thơm 5 kg", "Túi", 95000m, 120000m, 50m),
            ("Sữa tươi 1 lít", "Hộp", 25000m, 32000m, 8m),
