                db.PurchaseOrders.Add(po);
            }
            for (var day = 0; day < 7; day++)
            {
                // Today's invoices are in the past, including when seeded early in the morning.
                var soldAt = now.AddDays(-day).AddMinutes(-10);
                var product = products[day % products.Count];
                var qty = 2 + day;
                var order = new Order { TenantId = tenantId, BranchId = branch.Id, OrderCode = $"DM-{tag}-HD-{index}-{day}",
                    OrderDate = soldAt, CreatedAt = soldAt, BusinessDate = DateOnly.FromDateTime(soldAt.AddHours(7)),
                    TotalAmount = product.SellingPrice * qty, FinalAmount = product.SellingPrice * qty,
                    Status = "Completed", PaymentStatus = "PAID", PaymentMethod = "CASH", CashierName = "Thu ngân Demo" };
