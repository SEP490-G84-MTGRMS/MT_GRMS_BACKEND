            ("Nước suối 500 ml", "Chai", 2500m, 5000m, 100m),
            ("Dầu ăn 1 lít", "Chai", 36000m, 45000m, 4m) })
        {
            var product = new Product { TenantId = tenantId, CategoryId = category.Id, ProductCode = $"DM-{tag}-SP-{products.Count + 1:00}",
                Name = name, BaseUnit = unit, CostPrice = cost, SellingPrice = price, MinStock = 10, HasBatches = true };
            product.Units.Add(new ProductUnit { TenantId = tenantId, ProductId = product.Id, UnitName = unit,
                ConversionRate = 1, Price = price, IsBaseUnit = true, IsPurchaseUnit = true });
            products.Add(product);
            db.Products.Add(product);
            foreach (var branch in branches)
            {
                db.BranchProducts.Add(new BranchProduct { TenantId = tenantId, BranchId = branch.Id, ProductId = product.Id });
                db.BranchStocks.Add(new BranchStock { TenantId = tenantId, BranchId = branch.Id, ProductId = product.Id,
