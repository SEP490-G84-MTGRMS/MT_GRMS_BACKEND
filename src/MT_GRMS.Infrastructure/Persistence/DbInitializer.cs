    private static async Task SeedPurchasesAsync(AppDbContext db, Tenant tenant, Scenario scenario, CancellationToken ct)
    {
        var plan = await db.SubscriptionPlans.SingleAsync(p => p.PlanCode == scenario.Plan, ct);
        var months = scenario.Key == "pro-extra" ? 12 : scenario.Key == "pro" ? 3 : 1;
        var basePrice = months == 12 ? plan.PriceYearly : plan.PriceMonthly * months;
        var addon = scenario.Plan == "STANDARD" ? 30000m * months : scenario.Key == "pro-extra" ? 80000m * months : 0;
        var vat = Math.Round(basePrice * 0.1m, 2);
        var total = basePrice + vat + addon;
        var purchaseAt = tenant.FirstPaidAt!.Value;
        db.WalletTransactions.Add(new WalletTransaction { TenantId = tenant.Id, TransactionCode = "DEMO-" + scenario.Key + "-TOPUP",
            Type = "TOPUP", Amount = total, BalanceBefore = 0, BalanceAfter = total, PaymentMethod = "BANK_TRANSFER",
            Status = "SUCCESS", Description = "Nạp ví demo để mua gói", CreatedAt = purchaseAt.AddMinutes(-1), CompletedAt = purchaseAt.AddMinutes(-1) });
        db.WalletTransactions.Add(new WalletTransaction { TenantId = tenant.Id, TransactionCode = "DEMO-" + scenario.Key + "-PLAN",
            Type = "PURCHASE_PLAN", Amount = basePrice + vat, BalanceBefore = total, BalanceAfter = addon, PaymentMethod = "WALLET",
            Status = "SUCCESS", Description = $"Demo mua {scenario.Plan} ({months} tháng)", CreatedAt = purchaseAt, CompletedAt = purchaseAt });
        if (addon > 0)
            db.WalletTransactions.Add(new WalletTransaction { TenantId = tenant.Id, TransactionCode = "DEMO-" + scenario.Key + "-ADDON",
                Type = "PURCHASE_ADDON", Amount = addon, BalanceBefore = addon, BalanceAfter = 0, PaymentMethod = "WALLET",
                Status = "SUCCESS", Description = scenario.Plan == "STANDARD" ? "Demo mua quản lý nhân viên" : "Demo mua thêm 1 chi nhánh",
                CreatedAt = purchaseAt.AddSeconds(1), CompletedAt = purchaseAt.AddSeconds(1) });
    }

    private static async Task SeedOperationsAsync(AppDbContext db, string tenantId, List<Branch> branches, DateTime now, CancellationToken ct)
    {
